// Generating the Gleam modules that hold a project's SQL migrations, for
// `rays/durable_object/sql`.
//
// Every directory under `src/` named `migrations` that holds `.sql` files
// gets a module beside it: `src/app/notes/migrations/*.sql` becomes
// `src/app/notes/migrations.gleam`, whose constant `all` lists them in the
// order of their file names. It is written before Gleam compiles the
// project, so the project's code can import it, and only when it changes,
// so a watcher doesn't rebuild for nothing. A generated module whose
// directory no longer holds any `.sql` files is deleted.

import { existsSync, readdirSync, readFileSync, rmSync } from "node:fs";
import path from "node:path";
import { BuildError } from "./error.ts";
import { readIfExistsSync, writeAtomicallySync } from "./files.ts";
import { runGleamSync } from "./gleam.ts";
import { isModuleName } from "./module-name.ts";

/** The name of the directories whose `.sql` files are migrations. */
const MIGRATIONS_DIR = "migrations";

/** How a generated module starts, so rays knows it may write over it. */
const HEADER = "//// Generated by rays";

/**
 * Write the migrations module for each `migrations` directory under the
 * project's `src/` that holds `.sql` files, and delete each generated one
 * whose directory doesn't.
 *
 * It is synchronous, so the synchronous configuration that compiles the
 * project can write them first too.
 *
 * @throws {BuildError} If a directory isn't where a Gleam module can be,
 *   a module there wasn't generated by rays, or Gleam can't format one.
 */
export function writeMigrationModules(root: string, gleam: string): void {
  const src = path.join(root, "src");
  for (const [dir, files] of findMigrations(src)) {
    const relative = path.relative(src, dir).split(path.sep).join("/");
    const where = `src/${relative}`;
    const file = `${dir}.gleam`;
    const existing = readIfExistsSync(file);
    const generated = existing?.startsWith(HEADER) ?? false;

    if (files.length === 0) {
      if (generated) rmSync(file);
      continue;
    }
    if (existing !== undefined && !generated) {
      throw new BuildError(
        `${where}.gleam wasn't generated by rays, so rays won't write the migrations in ${where}/ over it. Rename one of them.`,
      );
    }
    if (!isModuleName(relative)) {
      throw new BuildError(
        `${where} holds migrations, but "${relative}" is not a Gleam module name, so rays can't write its module. Directories under src/ must be lowercase, like "app/notes/migrations".`,
      );
    }

    const migrations = files.map((name) => ({
      name: name.slice(0, -".sql".length),
      sql: readFileSync(path.join(dir, name), "utf8"),
    }));
    const source = runGleamSync(
      gleam,
      root,
      ["format", "--stdin"],
      migrationsSource(where, migrations),
    );
    if (existing !== source) writeAtomicallySync(file, source);
  }
}

/**
 * Every `migrations` directory under `src`, and every `migrations` directory
 * a `migrations.gleam` module sits beside, even if it doesn't exist, each
 * with the names of the `.sql` files in it, in order.
 */
function findMigrations(src: string): [string, string[]][] {
  const found = new Map<string, string[]>();
  const visit = (dir: string) => {
    const entries = readdirSync(dir, { withFileTypes: true });
    if (path.basename(dir) === MIGRATIONS_DIR) {
      found.set(
        dir,
        entries
          .filter((entry) => entry.isFile() && entry.name.endsWith(".sql"))
          .map((entry) => entry.name)
          .sort(compareNames),
      );
    }
    for (const entry of entries) {
      const child = path.join(dir, entry.name);
      if (entry.isDirectory()) {
        visit(child);
      } else if (entry.name === `${MIGRATIONS_DIR}.gleam`) {
        const beside = path.join(dir, MIGRATIONS_DIR);
        if (!found.has(beside)) found.set(beside, []);
      }
    }
  };
  if (existsSync(src)) visit(src);
  return [...found].sort(([a], [b]) => compareNames(a, b));
}

// By code point, so the order doesn't depend on the locale.
function compareNames(a: string, b: string): number {
  return a < b ? -1 : a > b ? 1 : 0;
}

/**
 * The source of a migrations module, before formatting.
 *
 * @param where The directory the migrations are in, such as
 *   `"src/app/notes/migrations"`.
 */
function migrationsSource(
  where: string,
  migrations: readonly { name: string; sql: string }[],
): string {
  const entries = migrations
    .map(
      ({ name, sql }) =>
        `  Migration(name: ${gleamString(name)}, sql: ${gleamString(sql)}),\n`,
    )
    .join("");
  return `${HEADER} from the .sql files in ${where}/.
//// Don't edit it: change those files, and rays writes it again when it
//// builds the project.

import rays/durable_object/sql.{type Migration, Migration}

/// The migrations, in the order of their file names, for \`sql.migrate\`.
pub const all: List(Migration) = [
${entries}]
`;
}

/** A Gleam string literal holding `text`. */
function gleamString(text: string): string {
  return `"${text.replace(/\\/g, "\\\\").replace(/"/g, '\\"')}"`;
}
