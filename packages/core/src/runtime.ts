/**
 * Use a rays Worker from TypeScript.
 *
 * A rays Worker, returned by a Gleam `main()` built with `rays/worker`, is
 * already a Cloudflare `ExportedHandler`. `handler()` checks that and types
 * it, so you can export it from an entry module or call it from your own
 * Worker:
 *
 * ```ts
 * import { handler } from "@rays/core/runtime";
 * import { main } from "./build/dev/javascript/my_app/my_app.mjs";
 *
 * const app = handler<Env>(main());
 *
 * export default {
 *   fetch(request, env, ctx) {
 *     const url = new URL(request.url);
 *     if (url.pathname.startsWith("/api/")) return app.fetch(request, env, ctx);
 *     return new Response("Hello from TypeScript");
 *   },
 * } satisfies ExportedHandler<Env>;
 * ```
 *
 * @module
 */

// Set to `true` on every Worker built by `rays/worker`. This is part of the
// Worker's documented runtime shape, along with its `fetch` method.
const WORKER_BRAND = Symbol.for("rays.worker");

/** A rays Worker, typed as the Cloudflare `ExportedHandler` it is. */
export type RaysHandler<Env = unknown> = ExportedHandler<Env> & {
  fetch: NonNullable<ExportedHandler<Env>["fetch"]>;
};

/**
 * Type a rays Worker as an `ExportedHandler`.
 *
 * The Worker is returned unchanged: this only checks it and gives it a type.
 * Pass the `Env` type of your bindings, such as the one generated by
 * `wrangler types`, to type the `env` argument of `fetch`.
 *
 * @param worker The result of calling a Gleam `main()` that returns a
 *   `worker.Worker`.
 * @throws {TypeError} If `worker` is not a rays Worker, for example because
 *   `main` was passed instead of `main()`.
 */
export function handler<Env = unknown>(worker: unknown): RaysHandler<Env> {
  if (hasWorkerBrand(worker)) {
    return worker;
  }

  const expected =
    "handler() expects a rays Worker, the result of calling a Gleam main()";

  if (typeof worker === "function") {
    throw new TypeError(
      `${expected}, but got a function. Did you mean handler(main())?`,
    );
  }

  if (worker === null) {
    throw new TypeError(`${expected}, but got null.`);
  }

  if (typeof worker === "object") {
    throw new TypeError(`${expected}, but got a different object.`);
  }

  throw new TypeError(`${expected}, but got ${typeof worker}.`);
}

function hasWorkerBrand(value: unknown): value is RaysHandler {
  return (
    typeof value === "object" &&
    value !== null &&
    (value as Record<symbol, unknown>)[WORKER_BRAND] === true
  );
}
