// Tests the migrations modules that `compile` writes for
// `rays/durable_object/sql`, against a real Gleam compiler.

import { execFileSync } from "node:child_process";
import { readFile, rm, stat } from "node:fs/promises";
import path from "node:path";
import { describe, expect, it } from "vitest";
import { BuildError, compile, readDurableObjectClasses } from "../src/build.ts";
import { useFixture } from "./fixture.ts";

const fixture = useFixture();
const write = (file: string, contents: string) => fixture.write(file, contents);
const read = (file: string) => readFile(path.join(fixture.root, file), "utf8");

describe("migrations modules", () => {
  it("lists a directory's .sql files in the order of their names", async () => {
    await write(
      "src/app/notes/migrations/0002_index.sql",
      "create index notes_by_body on notes (body);\n",
    );
    await write(
      "src/app/notes/migrations/0001_create.sql",
      'create table notes (\n  id integer primary key,\n  body text not null default "\\"\n);\n',
    );
    await write("src/app/notes/migrations/README.md", "Not a migration.\n");
    await compile({ root: fixture.root });

    expect(await read("src/app/notes/migrations.gleam")).toBe(
      `//// Generated by rays from the .sql files in src/app/notes/migrations/.
//// Don't edit it: change those files, and rays writes it again when it
//// builds the project.

import rays/durable_object/sql.{type Migration, Migration}

/// The migrations, in the order of their file names, for \`sql.migrate\`.
pub const all: List(Migration) = [
  Migration(
    name: "0001_create",
    sql: "create table notes (
  id integer primary key,
  body text not null default \\"\\\\\\"
);
",
  ),
  Migration(
    name: "0002_index",
    sql: "create index notes_by_body on notes (body);
",
  ),
]
`,
    );
  });

  it("writes a module the project can import, that gleam format accepts", async () => {
    await write("src/app/migrations/0001_create.sql", "create table t (a);");
    await write(
      "src/app/uses_migrations.gleam",
      "import app/migrations\nimport gleam/list\n\npub fn count() -> Int {\n  list.length(migrations.all)\n}\n",
    );
    await compile({ root: fixture.root });

    execFileSync("gleam", ["format", "--check", "src/app/migrations.gleam"], {
      cwd: fixture.root,
      stdio: "pipe",
    });
  });

  it("doesn't touch a module that is up to date", async () => {
    await write("src/app/migrations/0001_create.sql", "create table t (a);");
    await compile({ root: fixture.root });
    const file = path.join(fixture.root, "src/app/migrations.gleam");
    const before = (await stat(file)).mtimeMs;

    await compile({ root: fixture.root });
    expect((await stat(file)).mtimeMs).toBe(before);
  });

  it("writes the module again when a migration changes", async () => {
    await write("src/app/migrations/0001_create.sql", "create table t (a);");
    await compile({ root: fixture.root });
    await write("src/app/migrations/0002_more.sql", "create table u (b);");
    await compile({ root: fixture.root });

    expect(await read("src/app/migrations.gleam")).toContain(
      'Migration(name: "0002_more", sql: "create table u (b);")',
    );
  });

  it("is written by the synchronous class reader too", async () => {
    await write("src/app/migrations/0001_create.sql", "create table t (a);");
    readDurableObjectClasses({ root: fixture.root });

    expect(await read("src/app/migrations.gleam")).toContain(
      'Migration(name: "0001_create", sql: "create table t (a);")',
    );
  });

  it("ignores a migrations directory with no .sql files", async () => {
    await write("src/app/migrations/notes.txt", "Nothing here.\n");
    await compile({ root: fixture.root });

    await expect(
      stat(path.join(fixture.root, "src/app/migrations.gleam")),
    ).rejects.toThrow();
  });

  it("deletes a generated module once its directory has no .sql files", async () => {
    await write("src/app/migrations/0001_create.sql", "create table t (a);");
    await compile({ root: fixture.root });
    await rm(path.join(fixture.root, "src/app/migrations"), {
      recursive: true,
    });
    await compile({ root: fixture.root });

    await expect(
      stat(path.join(fixture.root, "src/app/migrations.gleam")),
    ).rejects.toThrow();
  });

  it("keeps a module rays didn't generate that has no migrations", async () => {
    await write("src/app/migrations.gleam", "pub const all = []\n");
    await compile({ root: fixture.root });

    expect(await read("src/app/migrations.gleam")).toBe("pub const all = []\n");
  });

  it("won't write over a module rays didn't generate", async () => {
    await write("src/app/migrations.gleam", "pub const all = []\n");
    await write("src/app/migrations/0001_create.sql", "create table t (a);");

    const error = await compile({ root: fixture.root }).catch((e) => e);
    expect(error).toBeInstanceOf(BuildError);
    expect(error.message).toBe(
      "src/app/migrations.gleam wasn't generated by rays, so rays won't write the migrations in src/app/migrations/ over it. Rename one of them.",
    );
    expect(await read("src/app/migrations.gleam")).toBe("pub const all = []\n");
  });

  it("refuses a directory that isn't where a module can be", async () => {
    await write("src/App/migrations/0001_create.sql", "create table t (a);");

    const error = await compile({ root: fixture.root }).catch((e) => e);
    expect(error).toBeInstanceOf(BuildError);
    expect(error.message).toBe(
      'src/App/migrations holds migrations, but "App/migrations" is not a Gleam module name, so rays can\'t write its module. Directories under src/ must be lowercase, like "app/notes/migrations".',
    );
  });
});
